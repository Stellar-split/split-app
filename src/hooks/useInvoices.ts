"use client";

import { useCallback, useEffect, useState } from "react";
import type { Invoice } from "@stellar-split/sdk";
import {
  clearInvoiceCache,
  getCachedInvoices,
  putCachedInvoices,
  QuotaExceededCacheError,
} from "@/lib/db/invoiceCache";
import { useToast } from "@/contexts/ToastContext";

/**
 * Bundle/schedule linkage metadata for an invoice. These fields are optional
 * because not every invoice belongs to a bundle or a recurring schedule.
 */
export interface InvoiceLinkage {
  /** Identifier of the bundle this invoice belongs to, if any. */
  bundleId?: string;
  /** Identifier of the recurring schedule that generated this invoice, if any. */
  scheduleId?: string;
}

/** An invoice enriched with its bundle/schedule linkage metadata. */
export type LinkedInvoice = Invoice & InvoiceLinkage;

export interface UseInvoicesResult {
  invoices: LinkedInvoice[];
  /** True until either the cache or the network has produced a first result. */
  loading: boolean;
  /** True while the network request is in flight, even after cached data painted. */
  refreshing: boolean;
  error: string | null;
  /** Wipes the IndexedDB cache; the next render still shows in-memory invoices. */
  clearCache: () => Promise<void>;
  /** Returns only invoices that belong to the given bundle. */
  filterByBundle: (bundleId: string) => LinkedInvoice[];
  /** Returns only invoices generated by the given recurring schedule. */
  filterBySchedule: (scheduleId: string) => LinkedInvoice[];
}

/**
 * Normalises a raw invoice payload into a LinkedInvoice, preserving any
 * bundle/schedule linkage fields the API may include.
 */
function toLinkedInvoice(invoice: Invoice): LinkedInvoice {
  const raw = invoice as Invoice & Partial<InvoiceLinkage>;
  return {
    ...invoice,
    bundleId: raw.bundleId,
    scheduleId: raw.scheduleId,
  };
}

/**
 * useInvoices — cache-then-network invoice list for a wallet address.
 *
 * On mount, cached invoices (if any) render immediately from IndexedDB while
 * the API request is in flight. When the API responds it becomes the
 * rendered list and is written back to the cache for the next cold load.
 */
export function useInvoices(publicKey: string | null | undefined): UseInvoicesResult {
  const [invoices, setInvoices] = useState<LinkedInvoice[]>([]);
  const [loading, setLoading] = useState(true);
  const [refreshing, setRefreshing] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const toast = useToast();

  useEffect(() => {
    let active = true;

    if (!publicKey) {
      setInvoices([]);
      setLoading(false);
      setRefreshing(false);
      return;
    }

    setLoading(true);
    setRefreshing(true);

    getCachedInvoices(publicKey).then((cached) => {
      if (!active) return;
      if (cached.length > 0) {
        setInvoices(cached.map(toLinkedInvoice));
        setLoading(false);
      }
    });

    fetch(`/api/invoices?publicKey=${encodeURIComponent(publicKey)}`)
      .then((res) => {
        if (!res.ok) throw new Error(`Failed to fetch invoices (${res.status})`);
        return res.json() as Promise<{ invoices: Invoice[] }>;
      })
      .then(async (data) => {
        if (!active) return;
        const linked = data.invoices.map(toLinkedInvoice);
        setInvoices(linked);
        setError(null);
        try {
          await putCachedInvoices(publicKey, data.invoices);
        } catch (err) {
          if (err instanceof QuotaExceededCacheError) {
            toast.info("Storage is full — invoice caching is disabled for this session.");
          }
        }
      })
      .catch((err) => {
        if (active) setError(err instanceof Error ? err.message : String(err));
      })
      .finally(() => {
        if (active) {
          setLoading(false);
          setRefreshing(false);
        }
      });

    return () => {
      active = false;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [publicKey]);

  const clearCache = useCallback(async () => {
    await clearInvoiceCache();
  }, []);

  const filterByBundle = useCallback(
    (bundleId: string) => invoices.filter((invoice) => invoice.bundleId === bundleId),
    [invoices],
  );

  const filterBySchedule = useCallback(
    (scheduleId: string) => invoices.filter((invoice) => invoice.scheduleId === scheduleId),
    [invoices],
  );

  return {
    invoices,
    loading,
    refreshing,
    error,
    clearCache,
    filterByBundle,
    filterBySchedule,
  };
}

export default useInvoices;
