/* Multi-currency invoice support with automatic conversion (#874)            */
/* -------------------------------------------------------------------------- */

export type CurrencyCode = "XLM" | "USDC" | string;

export interface CurrencyRate {
  /** Base currency (e.g. "USD"). */
  base: CurrencyCode;
  /** Quote currency (e.g. "XLM"). */
  quote: CurrencyCode;
  /** Units of `quote` per one unit of `base`. */
  rate: number;
  /** Timestamp the rate was fetched, epoch ms. */
  fetchedAt: number;
  /** Source of the rate (e.g. "stellar-dex", "coingecko"). */
  source: string;
}

export interface RateLock {
  id: string;
  invoiceId: string;
  base: CurrencyCode;
  quote: CurrencyCode;
  rate: number;
  /** Amount in base currency that was locked. */
  baseAmount: bigint;
  /** Amount in quote currency computed at lock time. */
  quoteAmount: bigint;
  lockedAt: number;
  /** Timestamp the lock expires, epoch ms. */
  expiresAt: number;
  status: "active" | "expired" | "consumed";
}

export interface CurrencyHistoryEntry {
  id: string;
  invoiceId: string;
  base: CurrencyCode;
  quote: CurrencyCode;
  rate: number;
  baseAmount: bigint;
  quoteAmount: bigint;
  recordedAt: number;
  /** Optional reference to the rate lock used, if any. */
  rateLockId?: string;
}

export interface CurrencyConversionPreview {
  base: CurrencyCode;
  quote: CurrencyCode;
  baseAmount: bigint;
  quoteAmount: bigint;
  rate: number;
  rateFetchedAt: number;
  rateLock: RateLock | null;
}

