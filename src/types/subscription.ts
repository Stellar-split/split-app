/* -------------------------------------------------------------------------- */
/* Recurring invoice templates with customizable schedules (#873)             */
/* -------------------------------------------------------------------------- */

export type RecurringFrequency = "daily" | "weekly" | "monthly" | "custom";

export type RecurringScheduleStatus = "active" | "paused" | "cancelled";

export interface RecurringScheduleHistoryEntry {
  id: string;
  /** Timestamp at which the run occurred or was attempted. */
  runAt: number;
  /** Invoice generated by this run, if any. */
  invoiceId: string | null;
  status: "generated" | "skipped" | "failed" | "paused" | "cancelled";
  amount: bigint;
  token: string;
  /** Optional human-readable note (e.g. failure reason). */
  note?: string;
}

export interface RecurringSchedule {
  id: string;
  templateId: string;
  creator: string;
  frequency: RecurringFrequency;
  /** Interval in days. Used directly for `custom`; derived for other frequencies. */
  intervalDays: number;
  /** Start of the schedule window (inclusive), epoch ms. */
  startDate: number;
  /** End of the schedule window (exclusive), epoch ms. Null means no end. */
  endDate: number | null;
  /** IANA timezone identifier, e.g. "America/New_York". */
  timezone: string;
  status: RecurringScheduleStatus;
  /** Next scheduled run, epoch ms. Null when paused/cancelled or exhausted. */
  nextRunDate: number | null;
  /** Last successful run, epoch ms. */
  lastRunDate: number | null;
  createdAt: number;
  updatedAt: number;
  history: RecurringScheduleHistoryEntry[];
}

export interface RecurringInvoiceTemplate {
  id: string;
  templateName: string;
  creator: string;
  recipients: Array<{ address: string; amount: bigint }>;
  token: string;
  /** Total amount per generated invoice. */
  amount: bigint;
  /** Payment deadline offset in days from generation. */
  deadlineDays: number;
  schedule: RecurringSchedule;
  createdAt: number;
  updatedAt: number;
}

export interface ScheduleConflict {
  /** The schedule that conflicts with the candidate schedule. */
  conflictingScheduleId: string;
  /** Timestamp at which the conflict occurs, epoch ms. */
  conflictAt: number;
  reason: "overlap" | "duplicate-run" | "invalid-window";
}

export interface ScheduleValidationResult {
  valid: boolean;
  errors: string[];
  conflicts: ScheduleConflict[];
}

export interface SchedulePreviewEntry {
  runAt: number;
  amount: bigint;
  token: string;
  deadline: number;
}

export interface SchedulePreview {
  scheduleId: string;
  entries: SchedulePreviewEntry[];
  totalAmount: bigint;
  /** Number of runs previewed (may be capped). */
  runCount: number;
}

